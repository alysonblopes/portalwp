/* Nexus ERP — service worker
   Cacheia só o "shell" do app (HTML/manifest/ícones) para abrir instalado
   e funcionar offline na parte de navegação. Chamadas ao Supabase e a
   CDNs externas (fontes, supabase-js) NÃO passam por aqui — precisam de
   rede mesmo. */

const CACHE_NAME = 'nexus-erp-v1';
const CORE_ASSETS = [
  './',
  './index.html',
  './manifest.json',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png',
  './icons/apple-touch-icon.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(CORE_ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // deixa Supabase/CDN/fonts passarem direto

  // Network-first: sempre tenta buscar a versão mais nova; se falhar
  // (offline), cai pro cache; se nem isso, cai pro shell (SPA offline).
  event.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
        return res;
      })
      .catch(() => caches.match(req).then((cached) => cached || caches.match('./index.html')))
  );
});
